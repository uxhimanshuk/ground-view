const FIRST_COLON = /^([^:]+):/;

/**
 * Whether a pageview title is an encyclopedia article rather than a main page
 * or a utility page.
 * @param {string} title API title, underscores for spaces.
 * @param {{main: string[]}} heartland Edition entry.
 */
export function isArticleTitle(title, heartland) {
  if (typeof title !== 'string' || !title) return false;
  if (heartland.main.includes(title)) return false;
  const prefix = FIRST_COLON.exec(title)?.[1];
  if (prefix && UTILITY_NAMESPACES.has(prefix.toLowerCase())) return false;
  return true;
}
